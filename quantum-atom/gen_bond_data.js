// Precompute the exact H₂⁺ potential curves (1sσg bonding, 2pσu antibonding) and the protons'
// vibrational levels on the bonding curve.  usage: node gen_bond_data.js > bond_data.js
const H2p = require('./h2plus.js');
const R = [], Eg = [], Eu = [];
for (let r = 0.5; r <= 12.0001; r += 0.05){ R.push(+r.toFixed(2)); Eg.push(+H2p.solve(r, 0).E.toFixed(8)); Eu.push(+H2p.solve(r, 1).E.toFixed(8)); }
// vibration on a fine grid of the bonding curve (proton–proton reduced mass m_p/2)
const Rs = [], U = [];
for (let r = 0.6; r <= 14.0001; r += 0.02){ Rs.push(r); U.push(H2p.solve(r, 0).E); }
const vib = H2p.vibLevels(Rs, U, 1836.15267343 / 2, 6).map(v => +v.toFixed(8));
console.log('// generated by gen_bond_data.js: exact Born–Oppenheimer H₂⁺ curves (Hartree, bohr)');
console.log('const BOND_DATA = ' + JSON.stringify({ R, Eg, Eu, vib, Re: 1.997193, Emin: -0.60263462 }) + ';');
console.log("if (typeof module !== 'undefined') module.exports = BOND_DATA;");
