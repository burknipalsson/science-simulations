// Precompute hydrogen data for the page (n ≤ 8): level energies, Einstein A coefficients between
// (n,l) levels, wavelengths, and the angular branching among real orbitals (l,m) → (l',m').
// usage: node gen_atom_data.js > atom_data.js
const H = require('./hydrogen.js');
const NMAX = 8;
const levels = [];
for (let n = 1; n <= NMAX; n++) for (let l = 0; l < n; l++) levels.push([n, l]);
const A = {};
let total = {};
for (const [n, l] of levels){
  let sum = 0;
  for (const [n2, l2] of levels){
    if (n2 >= n || Math.abs(l2 - l) !== 1) continue;
    const a = H.einsteinA(n, l, n2, l2);
    A[`${n}${l}-${n2}${l2}`] = +a.toPrecision(6);
    sum += a;
  }
  total[`${n}${l}`] = +sum.toPrecision(6);
}
// angular branching: for a real orbital (l, m) decaying to l', the probability of each real m' is
// Σ_q |<l' m'| n̂_q |l m>|² normalised; integrals by quadrature on the sphere
const NT = 200, NP = 400;
function ang(l, m, l2, m2){
  let sx = 0, sy = 0, sz = 0;
  for (let i = 0; i < NT; i++){
    const th = (i + 0.5) / NT * Math.PI, st = Math.sin(th), ct = Math.cos(th);
    for (let j = 0; j < NP; j++){
      const ph = (j + 0.5) / NP * 2 * Math.PI, w = st * (Math.PI / NT) * (2 * Math.PI / NP);
      const f = H.Yreal(l, m, th, ph) * H.Yreal(l2, m2, th, ph) * w;
      sx += f * st * Math.cos(ph); sy += f * st * Math.sin(ph); sz += f * ct;
    }
  }
  return sx * sx + sy * sy + sz * sz;
}
const branch = {};
for (let l = 1; l < NMAX; l++) for (const l2 of [l - 1, l + 1]){
  if (l2 < 0 || l2 >= NMAX - 1) continue;
  for (let m = -l; m <= l; m++){
    const p = []; let s = 0;
    for (let m2 = -l2; m2 <= l2; m2++){ const v = ang(l, m, l2, m2); p.push(v); s += v; }
    branch[`${l},${m}>${l2}`] = p.map(v => +(v / s).toFixed(5));
  }
}
// l = 0 decays (s → p): each of the three p orbitals equally
for (let l2 = 1; l2 <= 1; l2++) branch[`0,0>1`] = [1 / 3, 1 / 3, 1 / 3].map(v => +v.toFixed(5));
const lam = {};
for (let n = 2; n <= NMAX; n++) for (let n2 = 1; n2 < n; n2++) lam[`${n}-${n2}`] = [+H.lambdaVac_nm(n, n2).toFixed(4), +H.lambdaAir_nm(n, n2).toFixed(4)];
const E = {}; for (let n = 1; n <= NMAX; n++) E[n] = +(H.Emu(n) * H.Ha_eV).toFixed(6);
console.log('// generated by gen_atom_data.js: hydrogen n ≤ ' + NMAX + ' (exact non-relativistic, reduced mass)');
console.log('const ATOM_DATA = ' + JSON.stringify({ NMAX, E, A, total, branch, lam }) + ';');
console.log("if (typeof module !== 'undefined') module.exports = ATOM_DATA;");
