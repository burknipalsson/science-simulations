// pack developed suspension states (DUMPALL lines from gpu_cases tube runs) into states.js:
// per state, cell centres (float32, µm) and vertex offsets from the centre (int16, nm), gzipped + base64
const fs = require('fs'), zlib = require('zlib');
const specs = [['t20', 'state_20.log', 20, 0.2], ['t30', 'state_30.log', 30, 0.2], ['f20', 'r20f5.log', 20, 0.2]]; // f20: fine grid (0.25 µm, 2562-vertex cells), 320 ms
let out = '// Developed suspension states for the arteriole scene (generated by pack_states.js; t20/t30: 400 ms on the coarse grid, f20: 320 ms on the fine grid; viscosity contrast 5)\nconst STATES = {\n';
for (const [key, file, D, H] of specs) {
  const line = fs.readFileSync(file, 'utf8').split('\n').filter(l => l.startsWith('DUMPALL ')).pop();
  const d = JSON.parse(line.slice(8)), N = d.cells.length, nv = d.cells[0].length;
  const cen = new Float32Array(N * 3), off = new Int16Array(N * nv * 3);
  d.cells.forEach((X, c) => {
    const m = [0, 1, 2].map(i => X.reduce((a, p) => a + p[i], 0) / nv);
    m[0] = ((m[0] % d.nx) + d.nx) % d.nx; // wrap the centre into the box (offsets keep the shape)
    const m0 = [0, 1, 2].map(i => X.reduce((a, p) => a + p[i], 0) / nv);
    cen.set([m[0], m[1] - d.cc, m[2] - d.cc], 3 * c); // relative to the tube axis
    X.forEach((p, v) => { for (let i = 0; i < 3; i++) off[3 * (c * nv + v) + i] = Math.round((p[i] - m0[i]) * 1000); });
  });
  const buf = Buffer.concat([Buffer.from(cen.buffer), Buffer.from(off.buffer)]), gz = zlib.gzipSync(buf, { level: 9 });
  out += `  ${key}: { D: ${D}, H: ${H}, L: ${d.nx}, N: ${N}, nv: ${nv}, b64: '${gz.toString('base64')}' },\n`;
  console.log(key, N, 'cells', (buf.length / 1024).toFixed(0), 'KB raw', (gz.length / 1024).toFixed(0), 'KB gz');
}
out += `};
// decode a state: [{ c: [x, r_y, r_z] µm (x along the tube, y/z from the axis), X: [[dx,dy,dz] µm per vertex] }]
async function loadState(key) {
  const s = STATES[key], bin = Uint8Array.from(atob(s.b64), ch => ch.charCodeAt(0));
  const buf = await new Response(new Blob([bin]).stream().pipeThrough(new DecompressionStream('gzip'))).arrayBuffer();
  const cen = new Float32Array(buf, 0, s.N * 3), off = new Int16Array(buf, s.N * 12, s.N * s.nv * 3);
  return Array.from({ length: s.N }, (_, c) => ({ c: [cen[3 * c], cen[3 * c + 1], cen[3 * c + 2]],
    X: Array.from({ length: s.nv }, (_, v) => [0, 1, 2].map(i => off[3 * (c * s.nv + v) + i] / 1000)) }));
}
`;
fs.writeFileSync('states.js', out);
